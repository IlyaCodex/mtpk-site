/* B242YA / uibusiness: one consent-aware initialization after Metrika is ready. */
(function () {
  'use strict';
  // Retired: the owner requested no allocation from the old tracking-number pool.
  // Kept as a no-op for old HTML references; current pages do not load this asset.
  return;
  if (window.__uiCalltrackingController) return;
  window.__uiCalltrackingController = true;

  var COUNTER = 112991420;
  var BASE_PHONE = '73512116597';
  var pendingClientId = false;
  var initialized = false;
  var loading = false;
  var attempts = 0;
  var timer = null;
  var phoneTargets = [];
  var tracker = null;
  var assignedPhone = '';

  function hasConsent() {
    try { if (localStorage.getItem('ui_cookie_consent')) return true; } catch (e) {}
    return /(?:^|; )ui_cookie_consent=/.test(document.cookie);
  }

  function isOurVisit() {
    var keys = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_content', 'utm_term', 'yclid', 'gclid', 'fbclid'];
    var params;
    try { params = new URLSearchParams(location.search); } catch (e) { return false; }
    // A new tagged visit must never inherit a previous advertising campaign.
    if (keys.some(function (key) { return !!params.get(key); })) {
      return /^AImarketing_/i.test(params.get('utm_campaign') || '') &&
        /^(yandex)$/i.test(params.get('utm_source') || '') &&
        /^(cpc)$/i.test(params.get('utm_medium') || '');
    }
    try {
      var raw = localStorage.getItem('ui_marketing_trace');
      if (!raw) {
        var match = document.cookie.match(/(?:^|; )ui_marketing_trace=([^;]*)/);
        if (match) raw = decodeURIComponent(match[1]);
      }
      var saved = JSON.parse(raw || '{}');
      return /^AImarketing_/i.test(saved.utm_campaign || '') &&
        /^yandex$/i.test(saved.utm_source || '') && /^cpc$/i.test(saved.utm_medium || '');
    } catch (e) { return false; }
  }

  function formatPhone(phone) {
    return '+7 (' + phone.slice(1, 4) + ') ' + phone.slice(4, 7) + '-' +
      phone.slice(7, 9) + '-' + phone.slice(9);
  }

  function normalizePhone(value) {
    var digits = String(value || '').replace(/\D/g, '');
    if (digits.length === 11 && digits[0] === '8') digits = '7' + digits.slice(1);
    return /^7\d{10}$/.test(digits) ? digits : '';
  }

  function replacePhoneText(text, phone) {
    return text.replace(/\+?\d[\d\s\u00a0()\-\u2011\u2013]{8,30}\d/g, function (value) {
      return normalizePhone(value) === BASE_PHONE ? formatPhone(phone) : value;
    });
  }

  function syncPhones() {
    var link = tracker && tracker.querySelector('a[href^="tel:"]');
    var phone = normalizePhone(link && link.getAttribute('href'));
    // A fallback/base number is not an allocated tracking number.
    if (phone === BASE_PHONE) phone = '';
    if (phone === assignedPhone) return;
    assignedPhone = phone;
    phoneTargets.forEach(function (target) {
      target.link.setAttribute('href', phone ? 'tel:+' + phone : target.href);
      target.texts.forEach(function (item) {
        item.node.nodeValue = phone ? replacePhoneText(item.value, phone) : item.value;
      });
      if (target.label) target.link.setAttribute('aria-label', phone ? replacePhoneText(target.label, phone) : target.label);
    });
    if (phone) console.info('[UI calltracking] Tracking number allocated for uibusiness');
  }

  function preparePhones() {
    // Use a single vendor target; mirror its allocation into the existing links.
    // This preserves icons/layout and avoids nested anchors generated by B242YA.
    document.querySelectorAll('a[href="tel:+' + BASE_PHONE + '"]').forEach(function (link) {
      var texts = [];
      var walker = document.createTreeWalker(link, NodeFilter.SHOW_TEXT);
      var node;
      while ((node = walker.nextNode())) texts.push({ node: node, value: node.nodeValue });
      phoneTargets.push({ link: link, href: link.getAttribute('href'), label: link.getAttribute('aria-label'), texts: texts });
      link.classList.remove('b242ya-call-tracker');
      if (link.parentElement) link.parentElement.classList.remove('b242ya-call-tracker');
    });
    tracker = document.createElement('span');
    tracker.className = 'b242ya-call-tracker';
    tracker.hidden = true;
    tracker.setAttribute('aria-hidden', 'true');
    var anchor = document.createElement('a');
    anchor.href = 'tel:+' + BASE_PHONE;
    anchor.textContent = formatPhone(BASE_PHONE);
    tracker.appendChild(anchor);
    document.body.appendChild(tracker);
    new MutationObserver(syncPhones).observe(tracker, { childList: true, subtree: true, attributes: true, characterData: true });
  }

  function initialize() {
    if (initialized || typeof window.B242YAInit !== 'function') return;
    try {
      window.B242YAInit({
        portal: 'https://uinduktor.bitrix24.ru/',
        pid: '6de41eb1d932b12cd4ec47ddc85ac1df',
        yaCounterId: COUNTER,
        callTrackingPoolName: 'aimarketing'
      });
      initialized = true;
      window.__uiAIMarketingCallTrackingStarted = true;
      if (timer) clearInterval(timer);
      console.info('[UI calltracking] B242YA started after Metrika Client ID');
      syncPhones();
    } catch (e) {
      console.warn('[UI calltracking] B242YA initialization failed');
    }
  }

  function loadVendor() {
    console.info('[UI calltracking] Metrika Client ID is ready');
    if (!tracker) preparePhones();
    if (typeof window.B242YAInit === 'function') { initialize(); return; }
    if (loading) return;
    loading = true;
    var script = document.createElement('script');
    script.id = 'b242ya-script-aimarketing';
    script.async = true;
    script.src = 'https://67p.b242ya.ru/static/js/b242ya.js?ui-20261002';
    script.addEventListener('load', initialize, { once: true });
    script.addEventListener('error', function () {
      loading = false;
      script.remove();
      console.warn('[UI calltracking] B242YA script could not be loaded');
    }, { once: true });
    document.head.appendChild(script);
  }

  function tryStart() {
    if (initialized || !document.body || !hasConsent() || !isOurVisit() ||
        pendingClientId || typeof window.ym !== 'function') return;
    pendingClientId = true;
    var timeout = setTimeout(function () { pendingClientId = false; }, 5000);
    try {
      window.ym(COUNTER, 'getClientID', function (clientId) {
        clearTimeout(timeout);
        pendingClientId = false;
        if (clientId && !initialized && hasConsent() && isOurVisit()) loadVendor();
      });
    } catch (e) { clearTimeout(timeout); pendingClientId = false; }
  }

  function arm() {
    if (initialized || !hasConsent() || !isOurVisit()) return;
    tryStart();
    if (!initialized && !timer) {
      attempts = 0;
      timer = setInterval(function () {
        tryStart();
        if (++attempts >= 120) {
          clearInterval(timer); timer = null;
          console.warn('[UI calltracking] Metrika readiness timed out; original business numbers remain unchanged');
        }
      }, 500);
    }
  }

  window.addEventListener('cookie-consent-accepted', arm);
  window.addEventListener('ui-analytics-started', arm);
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', arm, { once: true });
  else arm();
})();
