def patch(slug: str) -> bool:
    f = BASE / slug / "body.html"
    src = f.read_text(encoding="utf-8")
    d = DATA[slug]

    # 1) spec-osnovnye: вставить новые строки ПЕРЕД <tr><th>Доставка</th>
    extra_rows = [
        f"              <tr><th>Срок&nbsp;службы</th><td>{d['srok']}</td></tr>\n"
    ]
    for name, val in d["extra"]:
        extra_rows.append(
            f"              <tr><th>{name}</th><td>{val}</td></tr>\n"
        )
    target = "              <tr><th>Доставка</th>"
    if target not in src:
        raise RuntimeError(f"{slug}: «Доставка» row not found")
    if "Срок&nbsp;службы" in src:
        # idempotent — skip enrichment if already done
        return False
    src = src.replace(target, "".join(extra_rows) + target, 1)

    # 2) spec-opisanie: заменить ВСЁ содержимое между <h2>Описание</h2> и
    #    закрывающим </div> панели — оставить наш канон-1 + 2-й абзац про серию + 3-й.
    opis_re = re.compile(
        r'(<div class="spec__panel" id="spec-opisanie">\s*'
        r'<h2 class="spec__title">Описание</h2>)'
        r'(.*?)'
        r'(\s*</div>\s*\n\s*<!-- 3 — Совместимость -->)',
        re.DOTALL,
    )
    p2 = OPISANIE_P2_M if d["series"] == "m" else OPISANIE_P2_STD
    new_body = (
        f"\n          <p>{d['opisanie_p1']}</p>\n"
        f"          <p>{p2}</p>\n"
        f"          <p>{OPISANIE_P3}</p>\n        "
    )
    src2, n = opis_re.subn(rf"\1{new_body}\3", src, count=1)
    if n != 1:
        raise RuntimeError(f"{slug}: spec-opisanie not patched (matches={n})")

    f.write_text(src2, encoding="utf-8")
    return True


def main():
    changed = []
    skipped = []
    for slug in DATA:
        if patch(slug):
            changed.append(slug)
        else:
            skipped.append(slug)
    print(f"changed: {len(changed)}")
    for s in changed:
        print(f"  + {s}")
    if skipped:
        print(f"already done (skipped): {len(skipped)}")
        for s in skipped:
            print(f"  = {s}")


if __name__ == "__main__":
    main()
